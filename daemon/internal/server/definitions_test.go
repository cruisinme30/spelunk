// navigationWorkspace writes the repos of the editor-navigation mock:
// RetryPolicy defined in Python, TypeScript and Go, plus a vendored and a
// generated copy, in three repos. Marked copies come after the others.
func navigationWorkspace(t *testing.T) (*testClient, []protocol.Root) {
	t.Helper()
	root := testutil.WriteTree(t, map[string]string{
		"payments-api/src/payments/retry_policy.py":  "class RetryPolicy:\n    def next_delay(self, attempt):\n        return 2 ** attempt\n",
		"payments-api/third_party/tenacity/retry.py": "class RetryPolicy(retry_base):\n    pass\n",
		"payments-api/tests/payments/client_test.py": "def test_retry_policy_defaults():\n    pass\n",
		"web-checkout/src/api/policy.ts": "export interface RetryPolicy {\n  attempts: number;\n}\n\n" +
			"export function loadPolicy(name: string): RetryPolicy {\n  return { attempts: 2 };\n}\n",
		"shared-libs/go/retry/retry.go": "package retry\n\n// RetryPolicy says how often to retry.\ntype RetryPolicy struct {\n" +
			"\tMaxAttempts int\n}\n\nfunc NewRetryPolicy() RetryPolicy {\n\treturn RetryPolicy{MaxAttempts: 3}\n}\n",
		"shared-libs/go/retry/client.go": "package retry\n\nfunc Do(policy RetryPolicy) {}\n",
		"shared-libs/proto/retry_pb2.py": "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n" +
			"class RetryPolicy(_message.Message):\n    pass\n",
	})
	var roots []protocol.Root
	for _, name := range []string{"payments-api", "shared-libs", "web-checkout"} {
		roots = append(roots, protocol.Root{ID: name, Path: filepath.Join(root, name), Name: name})
	}
	client := newTestClient(t)
	client.mustInitialize(t, roots...)
	return client, roots
}

// findSymbols calls symbols/find and returns its answer.
func findSymbols(t *testing.T, client *testClient, params protocol.SymbolsFindParams) protocol.SymbolsFindResult {
	t.Helper()
	var result protocol.SymbolsFindResult
	if err := client.call(protocol.MethodSymbolsFind, params, &result); err != nil {
		t.Fatal(err)
	}
	return result
}

// describe names each match as "kind name repo/path:line:column", plus its
// mark if it has one, with paths from the repos' parent folder.
func describe(roots []protocol.Root, matches []protocol.SymbolMatch) []string {
	parent := filepath.Dir(roots[0].Path)
	var out []string
	for _, m := range matches {
		rel, _ := filepath.Rel(parent, m.Path)
		line := m.SymbolKind + " " + m.Name + " " + filepath.ToSlash(rel) + ":" +
			strconv.Itoa(m.Line) + ":" + strconv.Itoa(m.Column)
		if m.RankReason != "" {
			line += " " + m.RankReason
		}
		out = append(out, line)
	}
	return out
}

func wantSymbols(t *testing.T, what string, got, want []string) {
	t.Helper()
	if !slices.Equal(got, want) {
		t.Errorf("%s =\n  %s\nwant\n  %s", what, strings.Join(got, "\n  "), strings.Join(want, "\n  "))
	}
}

func TestSymbolsFindMatchesLettersInOrderAcrossReposAndLanguages(t *testing.T) {
	// @covers rpc:symbols/find screen:editor-navigation
	// cspell:ignore retpol
	client, roots := navigationWorkspace(t)
	got := describe(roots, findSymbols(t, client, protocol.SymbolsFindParams{Text: "retpol"}).Symbols)
	// The letters only need to come in order. Shorter names first, then by
	// repo; the vendored and the generated copy are left out.
	wantSymbols(t, "retpol", got, []string{
		"class RetryPolicy payments-api/src/payments/retry_policy.py:1:7",
		"type RetryPolicy shared-libs/go/retry/retry.go:4:6",
		"interface RetryPolicy web-checkout/src/api/policy.ts:1:18",
		"function NewRetryPolicy shared-libs/go/retry/retry.go:8:6",
		"function test_retry_policy_defaults payments-api/tests/payments/client_test.py:1:5",
	})
}

func TestSymbolsFindPutsExactNamesThenPrefixesThenTheRest(t *testing.T) {
	// @covers rpc:symbols/find
	client, roots := navigationWorkspace(t)
	got := describe(roots, findSymbols(t, client, protocol.SymbolsFindParams{Text: "Policy", Limit: 3}).Symbols)
	// No name is just "policy", so loadPolicy, which holds it, comes before
	// longer names; the limit keeps the best three.
	wantSymbols(t, "Policy limit 3", got, []string{
		"function loadPolicy web-checkout/src/api/policy.ts:5:17",
		"class RetryPolicy payments-api/src/payments/retry_policy.py:1:7",
		"type RetryPolicy shared-libs/go/retry/retry.go:4:6",
	})
	if got := findSymbols(t, client, protocol.SymbolsFindParams{Text: "  "}).Symbols; len(got) != 0 {
		t.Errorf("blank text found %d definitions, want none", len(got))
	}
	if got := findSymbols(t, client, protocol.SymbolsFindParams{Text: "zzzz"}).Symbols; len(got) != 0 {
		t.Errorf("zzzz found %d definitions, want none", len(got))
	}
}

func TestSymbolsFindMarksGeneratedAndVendoredWhenAskedFor(t *testing.T) {
	// @covers rpc:symbols/find
	client, roots := navigationWorkspace(t)
	result := findSymbols(t, client, protocol.SymbolsFindParams{Text: "RetryPolicy", Exact: true, IncludeGeneratedAndVendored: true})
	wantSymbols(t, "RetryPolicy with generated and vendored", describe(roots, result.Symbols), []string{
		"class RetryPolicy payments-api/src/payments/retry_policy.py:1:7",
		"type RetryPolicy shared-libs/go/retry/retry.go:4:6",
		"interface RetryPolicy web-checkout/src/api/policy.ts:1:18",
		"class RetryPolicy payments-api/third_party/tenacity/retry.py:1:7 vendored",
		"class RetryPolicy shared-libs/proto/retry_pb2.py:2:7 generated",
	})
}

func TestSymbolsFindExactNameKeepsTheCallersLanguage(t *testing.T) {
	// @covers rpc:symbols/find
	client, roots := navigationWorkspace(t)
	from := filepath.Join(roots[1].Path, "go", "retry", "client.go")
	result := findSymbols(t, client, protocol.SymbolsFindParams{Text: "RetryPolicy", Exact: true, LanguageOf: from})
	if result.Language != "go" {
		t.Errorf("language = %q, want go", result.Language)
	}
	wantSymbols(t, "RetryPolicy from Go", describe(roots, result.Symbols), []string{
		"type RetryPolicy shared-libs/go/retry/retry.go:4:6",
	})
	// Exact is exact: another case is another name.
	if got := findSymbols(t, client, protocol.SymbolsFindParams{Text: "retryPolicy", Exact: true}).Symbols; len(got) != 0 {
		t.Errorf("retryPolicy found %v, want nothing", describe(roots, got))
	}
	// With nothing in the caller's language, every language answers.
	shell := filepath.Join(roots[0].Path, "deploy.sh")
	result = findSymbols(t, client, protocol.SymbolsFindParams{Text: "RetryPolicy", Exact: true, LanguageOf: shell})
	if len(result.Symbols) != 3 {
		t.Errorf("from a shell script, RetryPolicy = %v, want the 3 in other languages", describe(roots, result.Symbols))
	}
}

func TestSymbolsFindLeavesOutWhatVSCodeExcludesAndDeletedFiles(t *testing.T) {
	// @covers rpc:symbols/find
	client, roots := navigationWorkspace(t)
	updateSettings(t, client, func(s *protocol.Settings) {
		s.EditorExcludes = []protocol.RootExcludes{{RootID: "shared-libs", Patterns: globPatterns("go")}}
	})
	waitUntil(t, "the excludes to apply", func() bool { return len(client.server.Settings().EditorExcludes) == 1 })
	got := describe(roots, findSymbols(t, client, protocol.SymbolsFindParams{Text: "RetryPolicy", Exact: true}).Symbols)
	wantSymbols(t, "RetryPolicy with go/ excluded", got, []string{
		"class RetryPolicy payments-api/src/payments/retry_policy.py:1:7",
		"interface RetryPolicy web-checkout/src/api/policy.ts:1:18",
	})

	deleted := filepath.Join(roots[0].Path, "src", "payments", "retry_policy.py")
	if err := os.Remove(deleted); err != nil {
		t.Fatal(err)
	}
	if err := client.conn.Notify(protocol.MethodWorkspaceDidChangeFiles, protocol.DidChangeFilesParams{
		Changes: []protocol.FileChange{{Path: deleted, Type: "deleted"}},
	}); err != nil {
		t.Fatal(err)
	}
	waitUntil(t, "the deleted file to leave", func() bool {
		return len(findSymbols(t, client, protocol.SymbolsFindParams{Text: "RetryPolicy", Exact: true}).Symbols) == 1
	})
}

func TestSymbolsFindSeesASavedNewDefinition(t *testing.T) {
	// @covers rpc:symbols/find
	client, roots := navigationWorkspace(t)
	file := filepath.Join(roots[1].Path, "go", "retry", "retry.go")
	content, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	content = append(content, "\nfunc ParseRetryPolicy(s string) RetryPolicy { return NewRetryPolicy() }\n"...)
	if err := os.WriteFile(file, content, 0o600); err != nil {
		t.Fatal(err)
	}
	if err := client.conn.Notify(protocol.MethodWorkspaceDidChangeFiles, protocol.DidChangeFilesParams{
		Changes: []protocol.FileChange{{Path: file, Type: "changed"}},
	}); err != nil {
		t.Fatal(err)
	}
	waitUntil(t, "the new definition", func() bool {
		got := describe(roots, findSymbols(t, client, protocol.SymbolsFindParams{Text: "ParseRetry"}).Symbols)
		return slices.Equal(got, []string{"function ParseRetryPolicy shared-libs/go/retry/retry.go:12:6"})
	})
}
