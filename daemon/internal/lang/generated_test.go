func TestIsVendored(t *testing.T) {
	cases := map[string]bool{
		"web/node_modules/lodash/index.js":   true,
		"vendor/github.com/pkg/errors/a.go":  true,
		"third_party/stripe_compat/retry.py": true,
		"web/dist/checkout.bundle.js":        true,
		"src/vendors.go":                     false, // a file name, not a folder
		"src/distance/metric.py":             false,
		"docs/third_party.md":                false,
	}
	for path, want := range cases {
		if got := IsVendored(path); got != want {
			t.Errorf("IsVendored(%q) = %v, want %v", path, got, want)
		}
	}
}

func TestIsGenerated(t *testing.T) {
	cases := []struct {
		path    string
		content string
		want    bool
	}{
		{"api/service.pb.go", "", true},
		{"web/app.min.js", "", true},
		{"web/app.min.css", "", true},
		{"src/schema.gen.ts", "", true},
		{"src/schema.ts", "// @generated by codegen\nexport type A = 1;\n", true},
		{"api/types.go", "// Code generated by stringer; DO NOT EDIT.\n\npackage api\n", true},
		{"payments/retry_pb2.py", "", true},
		{"payments/retry_pb2_grpc.py", "", true},
		{"payments/proto/retry.py", "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: retry.proto\n", true},
		{"web/api.ts", "/* This file was generated by openapi-generator. DO NOT EDIT. */\n", true},
		{"src/gen.go", "// Code generated by hand, edit freely.\n", false},
		{"config/settings.py", "# DO NOT EDIT below this line without asking the payments team.\n", false},
		{"src/pb2.py", "", false},
		{"src/client.py", "import logging\n", false},
	}
	for _, c := range cases {
		if got := IsGenerated(c.path, []byte(c.content)); got != c.want {
			t.Errorf("IsGenerated(%q, %q) = %v, want %v", c.path, c.content, got, c.want)
		}
	}
}

func TestAGeneratedMarkerPastTheHeaderDoesNotCount(t *testing.T) {
	content := strings.Repeat(" ", GeneratedHeaderBytes) + "// @generated\n"
	if IsGenerated("src/big.ts", []byte(content)) {
		t.Errorf("a marker after the first %d bytes should not make a file generated", GeneratedHeaderBytes)
	}
}

func TestIsGeneratedNameNeedsNoContent(t *testing.T) {
	if !IsGeneratedName("api/service.pb.go") || IsGeneratedName("api/types.go") {
		t.Error("IsGeneratedName should match service.pb.go by its name and not types.go")
	}
}
