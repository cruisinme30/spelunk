package lang

import (
	"bytes"
	"path"
	"slices"
	"strings"
)

// DefaultVendoredFolders are the folders that hold someone else's code, or
// a build's, unless the index.vendoredFolders setting names others.
var DefaultVendoredFolders = []string{"vendor", "node_modules", "third_party", "dist"}

// DefaultGeneratedSuffixes end the names of files that tools write, unless
// the index.generatedSuffixes setting lists others.
var DefaultGeneratedSuffixes = []string{
	".pb.go", "_gen.go", ".gen.go", ".gen.ts", // protoc, go generate, codegen
	"_pb2.py", "_pb2_grpc.py", "_pb2.pyi", // protoc's Python output
	".min.js", ".min.css", // minified bundles
}

// GeneratedHeaderBytes is how far into a file a generated-code marker is
// looked for.
const GeneratedHeaderBytes = 1024

// FileKinds says which files are vendored and which a tool wrote, by the
// index.vendoredFolders and index.generatedSuffixes settings.
type FileKinds struct {
	vendoredFolders   []string
	generatedSuffixes []string
}

// DefaultFileKinds go by DefaultVendoredFolders and DefaultGeneratedSuffixes.
var DefaultFileKinds = NewFileKinds(nil, nil)

// NewFileKinds returns the FileKinds of the settings' lists. A nil list
// stands for its default; blank entries, and the slashes around a folder's
// name, are dropped.
func NewFileKinds(vendoredFolders, generatedSuffixes []string) *FileKinds {
	if vendoredFolders == nil {
		vendoredFolders = DefaultVendoredFolders
	}
	if generatedSuffixes == nil {
		generatedSuffixes = DefaultGeneratedSuffixes
	}
	return &FileKinds{
		vendoredFolders:   cleaned(vendoredFolders, func(folder string) string { return strings.Trim(folder, "/ ") }),
		generatedSuffixes: cleaned(generatedSuffixes, strings.TrimSpace),
	}
}

// cleaned returns the non-empty results of clean on each of values.
func cleaned(values []string, clean func(string) string) []string {
	kept := make([]string, 0, len(values))
	for _, value := range values {
		if value = clean(value); value != "" {
			kept = append(kept, value)
		}
	}
	return kept
}

// IsVendored reports whether the file at filePath (slash-separated, relative
// to its repo) is in a vendored folder: by default vendor/, node_modules/,
// third_party/ or dist/.
func (k *FileKinds) IsVendored(filePath string) bool {
	dirs := strings.Split(path.Dir(filePath), "/")
	return slices.ContainsFunc(dirs, func(dir string) bool { return slices.Contains(k.vendoredFolders, dir) })
}

// IsGeneratedName reports whether a file's name says a tool wrote it:
// service.pb.go, app.min.js. It needs no content, so it also works on the
// files of a commit.
func (k *FileKinds) IsGeneratedName(filePath string) bool {
	base := path.Base(filePath)
	return slices.ContainsFunc(k.generatedSuffixes, func(suffix string) bool { return strings.HasSuffix(base, suffix) })
}

// IsGenerated reports whether a file was written by a tool: named like
// generated code, or marked near the top of content with @generated or
// with "DO NOT EDIT" beside the word generated, as Go ("Code generated …
// DO NOT EDIT.") and protoc ("Generated by the protocol buffer compiler.
// DO NOT EDIT!") write it.
func (k *FileKinds) IsGenerated(filePath string, content []byte) bool {
	if k.IsGeneratedName(filePath) {
		return true
	}
	head := content[:min(len(content), GeneratedHeaderBytes)]
	return bytes.Contains(head, []byte("@generated")) ||
		bytes.Contains(head, []byte("DO NOT EDIT")) && bytes.Contains(bytes.ToLower(head), []byte("generated"))
}
