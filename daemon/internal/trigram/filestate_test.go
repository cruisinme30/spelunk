func TestIsGeneratedAndIsVendoredFilterFiles(t *testing.T) {
	// @covers op:is screen:generated-vendored
	tests := []struct {
		query string
		want  []string
	}{
		{"RetryPolicy -is:generated -is:vendored", []string{
			"file src/retry_policy.py",
			"src/client.py:1 from payments.policies import RetryPolicy",
			"src/retry_policy.py:1 class RetryPolicy:",
		}},
		{"content:RetryPolicy is:generated", []string{
			"src/proto/retry.py:2 RetryPolicy = None",
			"src/proto/retry_pb2.py:1 _RETRYPOLICY = DESCRIPTOR.message_types_by_name['RetryPolicy']",
			"web/schema.ts:2 export type RetryPolicy = {};",
		}},
		{"content:RetryPolicy is:vendored", []string{
			"dist/checkout.bundle.js:1 var RetryPolicy=function(e){};",
			"third_party/stripe_compat/retry.py:1 class RetryPolicy(object):",
		}},
		{"i:generated OR i:vendored", []string{
			"file dist/checkout.bundle.js",
			"file src/proto/retry.py",
			"file src/proto/retry_pb2.py",
			"file third_party/stripe_compat/retry.py",
			"file web/schema.ts",
		}},
	}
	for _, tt := range tests {
		if got, _ := run(t, tt.query, ownedAndOthersRepo); !reflect.DeepEqual(got, tt.want) {
			t.Errorf("%s:\n got %q\nwant %q", tt.query, got, tt.want)
		}
	}
}

// The index settings decide which folders are vendored and which file
// name endings mark generated files.
func TestIsGeneratedAndIsVendoredFollowTheSettings(t *testing.T) {
	// @covers setting:index.vendoredFolders setting:index.generatedSuffixes
	settings := defaultSettings
	settings.VendoredFolders = []string{"third_party"}
	settings.GeneratedSuffixes = []string{".bundle.js"}
	for query, want := range map[string][]string{
		"content:RetryPolicy is:vendored": {"third_party/stripe_compat/retry.py:1 class RetryPolicy(object):"},
		"content:RetryPolicy is:generated": {
			"dist/checkout.bundle.js:1 var RetryPolicy=function(e){};",
			"src/proto/retry.py:2 RetryPolicy = None",
			"web/schema.ts:2 export type RetryPolicy = {};",
		},
	} {
		items, _ := runItems(t, query, settings, "", ownedAndOthersRepo)
		if got := summarize(items); !reflect.DeepEqual(got, want) {
			t.Errorf("%s:\n got %q\nwant %q", query, got, want)
		}
	}
}

func TestIsGeneratedAndIsVendoredSayWhatTheyLeftOut(t *testing.T) {
	// @covers screen:generated-vendored
	_, stats := run(t, "content:RetryPolicy -is:generated -is:vendored", ownedAndOthersRepo)
	got := map[string]int{}
	for _, note := range stats.Hidden {
		got[note.Filter] = note.Count
		if note.Undo.Title != "Remove "+note.Filter {
			t.Errorf("undo = %q, want Remove %s", note.Undo.Title, note.Filter)
		}
	}
	if want := map[string]int{"-is:generated": 3, "-is:vendored": 2}; !reflect.DeepEqual(got, want) {
		t.Errorf("hidden = %v, want %v: each filter credited with the matches only it left out", got, want)
	}
}
