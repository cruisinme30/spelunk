// Mapping spelunk.* configuration to protocol types, and root ids.
import assert from "node:assert/strict";
import { test } from "node:test";
import { rootId } from "../roots";
import {
  closeOnOpen,
  daemonSettings,
  MOVED_SETTINGS,
  movedValue,
  pinnedQueries,
  previewContextLines,
  recentQueriesLimit,
  uiSettings,
  watchedQueries,
  watchNotify,
  welcomeSettings,
  type ConfigReader,
} from "../settings";

function configWith(values: Record<string, unknown>): ConfigReader {
  return { get: <T>(key: string, fallback: T) => (key in values ? (values[key] as T) : fallback) };
}

test("root ids are the first 12 hex digits of sha256(path)", () => {
  assert.equal(rootId("/a"), "6a50dc858413");
});

test("daemon settings clamp counts and reject unknown history depths", () => {
  const settings = daemonSettings(configWith({ "results.count": 999_999, "index.historyDepth": "bogus" }), "/home/u");
  assert.equal(settings.defaultCount, 50_000);
  assert.equal(settings.historyDepth, "2y");
});

test("the order setting reaches both the daemon and the panel", () => {
  const config = configWith({ "results.order": "path" });
  assert.equal(daemonSettings(config, "/home/u").order, "path");
  assert.equal(uiSettings(config).order, "path");
});

test("the context lines setting reaches both the daemon and the panel, clamped to 0..3", () => {
  // @covers setting:results.contextLines
  const lines = (value: unknown) => {
    const config = configWith({ "results.contextLines": value });
    const forDaemon = daemonSettings(config, "/home/u").contextLines;
    assert.equal(uiSettings(config).contextLines, forDaemon, "the panel and the daemon agree");
    return forDaemon;
  };
  assert.equal(daemonSettings(configWith({}), "/home/u").contextLines, 0, "off by default");
  assert.equal(uiSettings(configWith({})).contextLines, 0);
  assert.equal(lines(2), 2);
  assert.equal(lines(3), 3);
  assert.equal(lines(9), 3, "at most 3");
  assert.equal(lines(-1), 0);
  assert.equal(lines(1.6), 2, "rounded");
  assert.equal(lines("2"), 0, "not a number");
  assert.equal(lines(Number.NaN), 0);
});

/** The settings the daemon gets for these configuration values, with /home/u as home. */
const settings = (values: Record<string, unknown>) => daemonSettings(configWith(values), "/home/u");

test("the search time limit and the index lists and interval reach the daemon, clamped", () => {
  // @covers setting:search.timeLimitMs setting:index.commitCheckSeconds setting:index.vendoredFolders setting:index.generatedSuffixes setting:index.codeownersFiles
  assert.equal(settings({ "search.timeLimitMs": 5000 }).timeLimitMs, 5000);
  assert.equal(settings({ "search.timeLimitMs": 1 }).timeLimitMs, 100, "at least 100 ms");
  assert.equal(settings({ "search.timeLimitMs": 1e9 }).timeLimitMs, 60_000, "at most a minute");
  assert.equal(settings({ "index.commitCheckSeconds": 0 }).commitCheckSeconds, 1, "at least a second");
  assert.equal(settings({ "index.commitCheckSeconds": 1e6 }).commitCheckSeconds, 3600, "at most an hour");
  const lists = settings({
    "index.vendoredFolders": ["external", 4],
    "index.generatedSuffixes": [],
    "index.codeownersFiles": ["meta/OWNERS"],
  });
  assert.deepEqual(lists.vendoredFolders, ["external"]);
  assert.deepEqual(lists.generatedSuffixes, [], "an empty list marks no file generated by its name");
  assert.deepEqual(lists.codeownersFiles, ["meta/OWNERS"]);
});

test("the preview's context lines come from ui.previewContextLines, clamped to 0..100", () => {
  // @covers setting:ui.previewContextLines
  assert.equal(previewContextLines(configWith({})), 7);
  assert.equal(previewContextLines(configWith({ "ui.previewContextLines": 20 })), 20);
  assert.equal(previewContextLines(configWith({ "ui.previewContextLines": -1 })), 0);
  assert.equal(previewContextLines(configWith({ "ui.previewContextLines": 500 })), 100);
  assert.equal(previewContextLines(configWith({ "ui.previewContextLines": "lots" })), 7);
});

/** The index location the daemon gets for an index.location setting, with /home/u as home. */
const location = (value: string) => daemonSettings(configWith({ "index.location": value }), "/home/u").location;

test("the index location expands ~ and ~/ but not ~user", () => {
  assert.equal(location("~/idx"), "/home/u/idx");
  assert.equal(location("~"), "/home/u");
  assert.equal(location("~alice/idx"), "~alice/idx");
});

test("search.caseSensitive is off, on or smart", () => {
  // @covers setting:search.caseSensitive
  for (const value of ["off", "on", "smart"]) {
    assert.equal(daemonSettings(configWith({ "search.caseSensitive": value }), "/h").caseSensitive, value);
    assert.equal(uiSettings(configWith({ "search.caseSensitive": value })).caseSensitive, value);
  }
  assert.equal(uiSettings(configWith({ "search.caseSensitive": true })).caseSensitive, "off", "not a value it takes");
});

test("a setting saved under its old key moves to its section, unless the new key has a value", () => {
  assert.deepEqual(MOVED_SETTINGS, {
    caseSensitive: "search.caseSensitive",
    wholeWord: "search.wholeWord",
    typingDelayMs: "search.typingDelayMs",
    defaultCount: "results.count",
    order: "results.order",
  });
  assert.equal(movedValue("defaultCount", 200), 200);
  assert.equal(movedValue("order", "path"), "path");
  assert.equal(movedValue("caseSensitive", "smart"), "smart");
  assert.equal(movedValue("caseSensitive", true), "on", "the boolean it was before smart");
  assert.equal(movedValue("caseSensitive", false), "off");
  assert.equal(movedValue("wholeWord", false), false, "false is a value too");
  assert.equal(movedValue("defaultCount", 200, 50), undefined, "the new key's value wins");
  assert.equal(movedValue("defaultCount"), undefined, "nothing saved");
});

test("the welcome page shows the saved preset and index choices, and an unknown preset as the default", () => {
  const config = configWith({ "shortcut.preset": "findInFiles", "index.historyDepth": "6m", "index.symbols": false });
  assert.deepEqual(welcomeSettings(config, true), {
    preset: "findInFiles",
    historyDepth: "6m",
    symbols: false,
    mac: true,
  });
  assert.equal(welcomeSettings(configWith({ "shortcut.preset": "bogus" }), false).preset, "quickOpen");
});

test("settings of the wrong type or out of range fall back to defaults the daemon accepts", () => {
  // @covers setting:results.count setting:index.maxFileSizeKB setting:index.exclude setting:search.caseSensitive setting:search.wholeWord
  const wrong = configWith({
    "search.caseSensitive": "yes",
    "search.wholeWord": 1,
    "results.count": "lots",
    "index.symbols": 1,
    "index.exclude": "**/dist/**",
    "index.includeIgnored": null,
    "index.maxFileSizeKB": 1.5,
    "index.location": 42,
    "index.historyDepth": ["all"],
    "results.order": "random",
    "results.contextLines": "two",
    "search.timeLimitMs": "slow",
    "index.vendoredFolders": "vendor",
    "index.generatedSuffixes": null,
    "index.codeownersFiles": 7,
    "index.commitCheckSeconds": [5],
  });
  assert.deepEqual(daemonSettings(wrong, "/home/u"), {
    caseSensitive: "off",
    wholeWord: false,
    defaultCount: 500,
    historyDepth: "2y",
    symbols: true,
    exclude: ["**/vendor/**", "**/node_modules/**", "**/*.min.js"],
    includeIgnored: false,
    maxFileSizeKB: 2,
    location: "/home/u/.spelunk/index",
    order: "best",
    contextLines: 0,
    timeLimitMs: 2000,
    vendoredFolders: ["vendor", "node_modules", "third_party", "dist"],
    generatedSuffixes: [
      ".pb.go",
      "_gen.go",
      ".gen.go",
      ".gen.ts",
      "_pb2.py",
      "_pb2_grpc.py",
      "_pb2.pyi",
      ".min.js",
      ".min.css",
    ],
    codeownersFiles: [".github/CODEOWNERS", "CODEOWNERS", "docs/CODEOWNERS"],
    commitCheckSeconds: 5,
  });
  const extremes = daemonSettings(
    configWith({
      "results.count": -5,
      "index.maxFileSizeKB": 1e300,
      "index.exclude": ["a", 3, null, "b"],
      "index.location": "",
    }),
    "/home/u",
  );
  assert.equal(extremes.defaultCount, 1);
  assert.equal(extremes.maxFileSizeKB, 1024 * 1024, "kept inside the daemon's int");
  assert.deepEqual(extremes.exclude, ["a", "b"]);
  assert.equal(extremes.location, "/home/u/.spelunk/index", "an empty location means the default");
  assert.equal(
    JSON.stringify(daemonSettings(configWith({ "results.count": Number.NaN }), "/h")).includes("null"),
    false,
  );
});

test("panel settings of the wrong type fall back to their defaults", () => {
  // @covers setting:search.typingDelayMs setting:open.trigger setting:ui.recentQueries
  const wrong = configWith({
    "search.typingDelayMs": "fast",
    "open.trigger": 2,
    "open.preview": "no",
    "ui.showParsedQuery": 0,
    "search.caseSensitive": "true",
    "search.wholeWord": "true",
    "ui.recentQueries": "many",
    "open.closeOnOpen": "false",
    "results.order": 1,
    "results.contextLines": true,
  });
  assert.deepEqual(uiSettings(wrong), {
    typingDelayMs: 120,
    openTrigger: "doubleClick",
    preview: true,
    showParsedQuery: true,
    caseSensitive: "off",
    wholeWord: false,
    order: "best",
    contextLines: 0,
  });
  assert.equal(recentQueriesLimit(wrong), 20, "not NaN, which would empty the recent list");
  assert.equal(closeOnOpen(wrong), true);
  assert.equal(recentQueriesLimit(configWith({ "ui.recentQueries": -3 })), 0);
  assert.equal(recentQueriesLimit(configWith({ "ui.recentQueries": 2.6 })), 3);
  assert.equal(uiSettings(configWith({ "search.typingDelayMs": Number.POSITIVE_INFINITY })).typingDelayMs, 120);
});

test("pinned queries keep their order, drop bad entries and blank names, and keep a query once", () => {
  const config = configWith({
    "ui.pinnedQueries": [
      { query: " sym:RetryPolicy ", name: " Retry policy " },
      { query: "since:2w timeout", name: "  " },
      { query: "sym:RetryPolicy", name: "again" },
      { query: "" },
      { name: "no query" },
      "a string",
      null,
      { query: "retry", name: 7 },
    ],
  });
  assert.deepEqual(pinnedQueries(config), [
    { query: "sym:RetryPolicy", name: "Retry policy" },
    { query: "since:2w timeout" },
    { query: "retry" },
  ]);
  assert.deepEqual(pinnedQueries(configWith({ "ui.pinnedQueries": "nope" })), []);
  assert.deepEqual(pinnedQueries(configWith({})), []);
});

test("a pinned query is watched only with watch: true, and the watched ones go to the daemon", () => {
  // @covers screen:query-watches
  const config = configWith({
    "ui.pinnedQueries": [
      { query: "msg:revert f:payments/", name: "Payments reverts", watch: true },
      { query: "author:jason", watch: "yes" },
      { query: "sym:RetryPolicy", watch: false },
      { query: " type:commit timeout ", watch: true },
    ],
  });
  assert.deepEqual(pinnedQueries(config), [
    { query: "msg:revert f:payments/", name: "Payments reverts", watch: true },
    { query: "author:jason" },
    { query: "sym:RetryPolicy" },
    { query: "type:commit timeout", watch: true },
  ]);
  assert.deepEqual(watchedQueries(config), ["msg:revert f:payments/", "type:commit timeout"]);
  assert.deepEqual(watchedQueries(configWith({})), []);
});

test("watch.notify pops up a watch's new commits unless it is off", () => {
  // @covers setting:watch.notify
  assert.equal(watchNotify(configWith({})), true, "on by default");
  assert.equal(watchNotify(configWith({ "watch.notify": false })), false);
  assert.equal(watchNotify(configWith({ "watch.notify": "no" })), true, "not a boolean: the default");
});
